function getLang() {
  return localStorage.getItem("lang") === "ar" ? "ar" : "en";
}

// t("key", {n: 5}) -> looks up key in current language, replaces {n} placeholders
function t(key, vars) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => { str = str.replace(`{${k}}`, vars[k]); });
  }
  return str;
}

function applyI18n() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph"))); });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
  document.querySelectorAll("[data-lang-btn]").forEach((el) => { el.textContent = t("common.langToggle"); });
}

function setLang(lang) {
  localStorage.setItem("lang", lang === "ar" ? "ar" : "en");
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange"));
}

function initLangToggle() {
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.addEventListener("click", () => setLang(getLang() === "ar" ? "en" : "ar"));
  });
}

// This script is loaded at the bottom of <body>, after all markup, so the DOM
// is already parsed — apply translations and wire the toggle immediately.
applyI18n();
initLangToggle();
